(function () {
  'use strict';
  var DICT = window.TOPLINE_I18N;
  var LANGS = ['al', 'it', 'en'];
  var HTML_LANG = { al: 'sq', it: 'it', en: 'en' };
  var STORE = 'topline-lang';

  function current() {
    try {
      var saved = localStorage.getItem(STORE);
      if (saved && LANGS.indexOf(saved) !== -1) return saved;
    } catch (e) {}
    return 'en';
  }

  function apply(lang) {
    var table = DICT[lang] || {};
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var v = table[el.getAttribute('data-i18n')];
      if (typeof v === 'string') el.innerHTML = v;
    });
    document.documentElement.setAttribute('lang', HTML_LANG[lang] || 'en');
    document.querySelectorAll('[data-lang-switch]').forEach(function (sw) {
      sw.querySelectorAll('.lang__opt').forEach(function (b) {
        var on = b.getAttribute('data-lang') === lang;
        b.classList.toggle('is-active', on);
        if (on) movePill(sw, b);
      });
    });
  }

  function movePill(sw, btn) {
    var pill = sw.querySelector('.lang__pill');
    if (!pill) return;
    pill.style.left = btn.offsetLeft + 'px';
    pill.style.width = btn.offsetWidth + 'px';
  }

  function set(lang) {
    try { localStorage.setItem(STORE, lang); } catch (e) {}
    apply(lang);
  }

  function init() {
    apply(current());
    document.querySelectorAll('[data-lang-switch] .lang__opt').forEach(function (b) {
      b.addEventListener('click', function () { set(b.getAttribute('data-lang')); });
    });
    // widths settle once the webfont lands
    if (document.fonts && document.fonts.ready) {
      document.fonts.ready.then(function () { apply(current()); });
    }
    window.addEventListener('resize', function () { apply(current()); });
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
